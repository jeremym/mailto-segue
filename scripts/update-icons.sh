#!/usr/bin/env bash
#
# Download the Simple Icons (CC0) marks Segue uses and generate
# Sources/Segue/Chooser/ServiceIcons.generated.swift with each SVG path and
# brand colour. Run at development time only; the app makes no network calls.
#
#   scripts/update-icons.sh [simple-icons version]   (default 16.35.0)
set -euo pipefail
cd "$(dirname "$0")/.."
VERSION="${1:-16.35.0}"
# provider → simple-icons slug
PAIRS="gmail:gmail proton:protonmail icloud:icloud hey:hey zoho:zoho tuta:tuta thunderbird:thunderbird"
OUT="Sources/Segue/Chooser/ServiceIcons.generated.swift"
DIR="Resources/ServiceIcons"
mkdir -p "$DIR"

{
    echo "// Generated by scripts/update-icons.sh from Simple Icons v$VERSION (CC0-1.0)."
    echo "// Do not edit by hand. Logos are trademarks of their owners, used only to identify each service."
    echo "enum ServiceIcons {"
    echo "    static let version = \"$VERSION\""
    echo "    struct Mark { let path: String; let hex: String }"
    echo "    static let marks: [String: Mark] = ["
} > "$OUT"

for pair in $PAIRS; do
    provider="${pair%%:*}"; slug="${pair##*:}"
    url="https://cdn.jsdelivr.net/npm/simple-icons@$VERSION/icons/$slug.svg"
    svg="$DIR/$slug.svg"
    curl -fsSL "$url" -o "$svg"
    path="$(sed -nE 's/.*<path d="([^"]+)".*/\1/p' "$svg" | head -1)"
    hex="$(curl -fsSL "https://cdn.jsdelivr.net/npm/simple-icons@$VERSION/data/simple-icons.json" 2>/dev/null \
        | python3 -I -c "import json,sys; d=json.load(sys.stdin); icons=d['icons'] if isinstance(d,dict) else d; print(next((i['hex'] for i in icons if i.get('slug','').lower()=='$slug' or i['title'].lower().replace(' ','')=='$slug'),''))" 2>/dev/null || true)"
    [[ -n "$path" ]] || { echo "error: no path in $svg" >&2; exit 1; }
    echo "        \"$provider\": Mark(path: \"$path\", hex: \"${hex:-000000}\")," >> "$OUT"
    echo "  $provider ← $slug (#${hex:-?})"
done

{
    echo "    ]"
    echo "}"
} >> "$OUT"

cat > "$DIR/README.md" <<MD
# Service icons

SVG marks from [Simple Icons](https://simpleicons.org) v$VERSION, licensed CC0-1.0
(public domain). Fetched by \`scripts/update-icons.sh\`, which also generates
\`Sources/Segue/Chooser/ServiceIcons.generated.swift\`. The logos are trademarks of
their respective owners and are used only to identify each service.
MD
echo "wrote $OUT"
